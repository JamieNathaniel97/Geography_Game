def ceremonial(name):
    """the facts for a ceremonial area: its own, or carried over from the historic county of the same name"""
    own = CEREMONIAL.get(name)
    if own is None:
        return dict(HISTORIC.get(name, {}))
    base = dict(HISTORIC.get(own.get("from"), {})) if "from" in own else {}
    for k, v in own.items():
        if k == "from":
            continue
        if v is None:
            base.pop(k, None)
        else:
            base[k] = v
    return base
